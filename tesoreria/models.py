# tesoreria/models.py
"""
Treasury domain.

This module concentrates everything related to where the money flows:

- ``MedioDePago``: catalog of payment methods (was ``core.MedioDePago``).
- ``AsignacionMedioPagoCajero``: links every cashier to the payment methods
  they are allowed to operate.
- ``MovimientoCuenta``: ledger of every inflow/outflow generated by the
  business operations (sales, expenses, supplier payments, debt collections,
  withdrawals, opening balances).
"""

from decimal import Decimal

from django.conf import settings
from django.contrib.contenttypes.fields import GenericForeignKey
from django.contrib.contenttypes.models import ContentType
from django.db import models
from django.utils import timezone
from django.utils.translation import gettext_lazy as _

from core.sync import DeSucursalMixin, IdentidadGlobalMixin


# Categorías históricas. Las claves se conservan tal cual quedaron en la base
# de datos para no romper datos existentes; las etiquetas se traducen.
MediosDePago = (
    ('Efectivo', _('Efectivo')),
    ('Cuenta Corriente', _('Cuenta corriente')),
    ('Tarjeta de Crédito', _('Tarjeta de crédito')),
    ('Tarjeta de Débito', _('Tarjeta de débito')),
    ('Transferencia Bancaria', _('Transferencia bancaria')),
    ('Otro', _('Otro')),
)


class MedioDePago(IdentidadGlobalMixin):
    """Catalog entry for a payment method.

    The underlying database table is preserved (``core_mediodepago``) so the
    move from ``core`` to ``tesoreria`` does not require any data migration.
    """

    nombre = models.CharField(
        max_length=200,
        blank=True,
        null=True,
        verbose_name=_("Nombre del medio de pago"),
        help_text=_("Etiqueta interna para este medio de pago."),
    )
    categoria = models.CharField(
        max_length=200,
        choices=MediosDePago,
        default='Efectivo',
        null=True,
        blank=True,
        verbose_name=_("Tipo de medio de pago"),
        help_text=_("Seleccioná la categoría del medio de pago."),
    )

    def __str__(self):
        return self.nombre or self.categoria or ''

    class Meta:
        db_table = 'core_mediodepago'
        verbose_name = _("Medio de pago")
        verbose_name_plural = _("Medios de pago")


class AsignacionMedioPagoCajero(IdentidadGlobalMixin):
    """Links a cashier user with the payment methods they may operate.

    If a cashier has at least one assignment, only the assigned methods are
    available in the POS. If a cashier has **no** assignments, all methods are
    available (backward-compatible default).
    """

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='medios_asignados',
        verbose_name=_("Cajero"),
        help_text=_("Cajero al que pertenece esta asignación."),
    )
    medio_de_pago = models.ForeignKey(
        MedioDePago,
        on_delete=models.CASCADE,
        related_name='asignaciones_cajero',
        verbose_name=_("Medio de pago"),
        help_text=_("Medio de pago permitido para el cajero."),
    )
    activo = models.BooleanField(
        default=True,
        verbose_name=_("Activo"),
        help_text=_("Desactivá para quitar el acceso del cajero sin eliminar la asignación."),
    )
    creado_en = models.DateTimeField(auto_now_add=True, verbose_name=_("Creado el"))

    class Meta:
        unique_together = ('user', 'medio_de_pago')
        verbose_name = _("Asignación de medio de pago a cajero")
        verbose_name_plural = _("Asignaciones de medios de pago a cajeros")
        ordering = ('user__username', 'medio_de_pago__nombre')

    def __str__(self):
        return f'{self.user.username} → {self.medio_de_pago}'


class MovimientoCuenta(DeSucursalMixin):
    """Ledger entry generated for every business cash event.

    A movement always belongs to one payment method and points back to the
    domain object that created it via a generic foreign key (``origen``).
    Movements are regenerated by signals so they always reflect the current
    state of the source object.
    """

    TIPO_VENTA = 'venta'
    TIPO_VENTA_PAGO = 'venta_pago'
    TIPO_GASTO = 'gasto'
    TIPO_PAGO_PROVEEDOR = 'pago_proveedor'
    TIPO_COBRO_DEUDA = 'cobro_deuda'
    TIPO_ADELANTO_CLIENTE = 'adelanto_cliente'
    TIPO_ADELANTO_PROVEEDOR = 'adelanto_proveedor'
    TIPO_CANCELACION_PROVEEDOR = 'cancelacion_proveedor'
    TIPO_RETIRO = 'retiro'
    TIPO_APERTURA = 'apertura_caja'
    TIPO_AJUSTE = 'ajuste'
    TIPO_TRANSFERENCIA = 'transferencia'
    TIPO_CIERRE_DIFERENCIA = 'cierre_diferencia'
    TIPO_CIERRE_DEVOLUCION = 'cierre_devolucion'

    TIPO_CHOICES = [
        (TIPO_VENTA, _('Venta')),
        (TIPO_VENTA_PAGO, _('Pago de venta')),
        (TIPO_GASTO, _('Gasto')),
        (TIPO_PAGO_PROVEEDOR, _('Pago a proveedor')),
        (TIPO_COBRO_DEUDA, _('Cobro de deuda de cliente')),
        (TIPO_ADELANTO_CLIENTE, _('Adelanto de cliente')),
        (TIPO_ADELANTO_PROVEEDOR, _('Adelanto de proveedor')),
        (TIPO_CANCELACION_PROVEEDOR, _('Cancelación de deuda a proveedor')),
        (TIPO_RETIRO, _('Retiro de efectivo')),
        (TIPO_APERTURA, _('Apertura de caja')),
        (TIPO_AJUSTE, _('Ajuste')),
        (TIPO_TRANSFERENCIA, _('Transferencia entre cuentas')),
        (TIPO_CIERRE_DIFERENCIA, _('Diferencia de arqueo de cierre')),
        (TIPO_CIERRE_DEVOLUCION, _('Devolución de efectivo al cierre')),
    ]

    SIGNO_INGRESO = 'ingreso'
    SIGNO_EGRESO = 'egreso'
    SIGNO_CHOICES = [
        (SIGNO_INGRESO, _('Ingreso')),
        (SIGNO_EGRESO, _('Egreso')),
    ]

    fecha = models.DateTimeField(
        default=timezone.now,
        db_index=True,
        verbose_name=_("Fecha"),
        help_text=_("Momento en que ocurrió el movimiento."),
    )
    medio_de_pago = models.ForeignKey(
        MedioDePago,
        on_delete=models.PROTECT,
        related_name='movimientos',
        verbose_name=_("Medio de pago"),
        help_text=_("Medio de pago afectado por este movimiento."),
    )
    tipo = models.CharField(
        max_length=32,
        choices=TIPO_CHOICES,
        db_index=True,
        verbose_name=_("Tipo"),
        help_text=_("Operación que originó el movimiento."),
    )
    signo = models.CharField(
        max_length=8,
        choices=SIGNO_CHOICES,
        default=SIGNO_INGRESO,
        verbose_name=_("Dirección"),
        help_text=_("Indica si el dinero entra o sale."),
    )
    monto = models.DecimalField(
        max_digits=14,
        decimal_places=2,
        verbose_name=_("Monto"),
        help_text=_("Siempre positivo; el signo se define en la dirección."),
    )
    usuario = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='movimientos_cuenta',
        verbose_name=_("Usuario"),
        help_text=_("Usuario que registró la operación de origen."),
    )
    turno = models.ForeignKey(
        'ventas.TurnoCaja',
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='movimientos_cuenta',
        verbose_name=_("Turno de caja"),
        help_text=_("Turno de caja al que pertenece el movimiento."),
    )
    descripcion = models.CharField(
        max_length=255,
        blank=True,
        verbose_name=_("Descripción"),
        help_text=_("Texto libre que describe el movimiento."),
    )
    content_type = models.ForeignKey(
        ContentType,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='movimientos_cuenta',
    )
    object_id = models.PositiveIntegerField(null=True, blank=True)
    origen = GenericForeignKey('content_type', 'object_id')

    class Meta:
        verbose_name = _("Movimiento de cuenta")
        verbose_name_plural = _("Movimientos de cuenta")
        ordering = ('-fecha', '-id')
        indexes = [
            models.Index(fields=['content_type', 'object_id']),
            models.Index(fields=['medio_de_pago', 'fecha']),
            models.Index(fields=['turno', 'medio_de_pago']),
        ]

    def __str__(self):
        sign = '+' if self.signo == self.SIGNO_INGRESO else '-'
        medio = self.medio_de_pago.nombre if self.medio_de_pago else '-'
        return f'{sign}${self.monto} {medio} ({self.get_tipo_display()})'

    @property
    def monto_signed(self):
        """Return the amount with the proper sign for accumulation."""
        if self.signo == self.SIGNO_EGRESO:
            return -self.monto
        return self.monto


