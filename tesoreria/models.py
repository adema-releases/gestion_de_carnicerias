def _get_configuracion():
    try:
        from core.models import Configuracion
        return Configuracion.objects.first()
    except Exception:
        return None


def get_cuenta_caja_pos():
    """Drawer account of the POS terminal. Falls back to the first Efectivo account."""
    cfg = _get_configuracion()
    if cfg and cfg.cuenta_caja_pos_id:
        return cfg.cuenta_caja_pos
    return get_efectivo_default()


def get_cuenta_caja_central():
    """Central cash account (treasury/safe). None if not configured."""
    cfg = _get_configuracion()
    if cfg and cfg.cuenta_caja_central_id:
        return cfg.cuenta_caja_central
    return None


def get_cuenta_diferencias_caja():
    """Virtual account accumulating cash-count differences. None if not configured."""
    cfg = _get_configuracion()
    if cfg and cfg.cuenta_diferencias_caja_id:
        return cfg.cuenta_diferencias_caja
    return None


def get_cuenta_mercado_pago():
    """Mercado Pago account. Falls back to name lookup for legacy installs."""
    cfg = _get_configuracion()
    if cfg and cfg.cuenta_mercado_pago_id:
        return cfg.cuenta_mercado_pago
    for medio in MedioDePago.objects.all():
        nombre = ' '.join((medio.nombre or '').strip().lower().split())
        if nombre == 'mercado pago':
            return medio
    return None


def saldo_cuenta(medio):
    """Current ledger balance of a payment method (Σ ingresos − Σ egresos)."""
    from django.db.models import Case, DecimalField, F, Sum, When

    if medio is None:
        return Decimal('0')
    agg = medio.movimientos.aggregate(
        saldo=Sum(
            Case(
                When(signo=MovimientoCuenta.SIGNO_INGRESO, then=F('monto')),
                When(signo=MovimientoCuenta.SIGNO_EGRESO, then=-F('monto')),
                default=Decimal('0'),
                output_field=DecimalField(max_digits=14, decimal_places=2),
            )
        )
    )
    return agg['saldo'] or Decimal('0')
