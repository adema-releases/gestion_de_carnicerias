class TransferenciaCuenta(DeSucursalMixin):
    """Registro de un movimiento de fondos entre dos medios de pago/cuentas.

    Al guardar se generan automáticamente dos ``MovimientoCuenta``: un egreso
    en la cuenta de origen y un ingreso en la cuenta de destino.
    """

    cuenta_origen = models.ForeignKey(
        MedioDePago,
        on_delete=models.PROTECT,
        related_name='transferencias_salientes',
        verbose_name=_("Cuenta origen"),
        help_text=_("Medio de pago / cuenta desde donde sale el dinero."),
    )
    cuenta_destino = models.ForeignKey(
        MedioDePago,
        on_delete=models.PROTECT,
        related_name='transferencias_entrantes',
        verbose_name=_("Cuenta destino"),
        help_text=_("Medio de pago / cuenta a donde va el dinero."),
    )
    monto = models.DecimalField(
        max_digits=14,
        decimal_places=2,
        verbose_name=_("Monto"),
        help_text=_("Importe a transferir. Siempre positivo."),
    )
    fecha = models.DateTimeField(
        default=timezone.now,
        db_index=True,
        verbose_name=_("Fecha"),
        help_text=_("Momento en que ocurrió la transferencia."),
    )
    descripcion = models.CharField(
        max_length=255,
        blank=True,
        verbose_name=_("Descripción"),
        help_text=_("Detalle opcional de la transferencia (ej: 'Fondo reserva → caja apertura')."),
    )
    usuario = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='transferencias_cuenta',
        verbose_name=_("Usuario"),
        help_text=_("Usuario que registró la transferencia."),
    )
    creado_en = models.DateTimeField(auto_now_add=True, verbose_name=_("Creado el"))

    class Meta:
        verbose_name = _("Transferencia entre cuentas")
        verbose_name_plural = _("Transferencias entre cuentas")
        ordering = ('-fecha', '-id')

    def __str__(self):
        return f'${self.monto} {self.cuenta_origen} → {self.cuenta_destino} ({self.fecha:%d/%m/%Y})'


