class AjusteCuenta(DeSucursalMixin):
    """Manual balance adjustment entry for a payment method account.

    Positive ``monto`` increases the balance (ingreso); negative decreases it
    (egreso). A ``MovimientoCuenta`` with ``tipo=TIPO_AJUSTE`` is regenerated
    automatically by a signal whenever this object is saved or deleted.
    """

    medio_de_pago = models.ForeignKey(
        MedioDePago,
        on_delete=models.PROTECT,
        related_name='ajustes',
        verbose_name=_("Cuenta / Medio de pago"),
        help_text=_("Cuenta a la que se aplica el ajuste."),
    )
    fecha = models.DateTimeField(
        default=timezone.now,
        db_index=True,
        verbose_name=_("Fecha"),
        help_text=_("Momento en que se registra el ajuste."),
    )
    monto = models.DecimalField(
        max_digits=14,
        decimal_places=2,
        verbose_name=_("Monto"),
        help_text=_("Positivo para acreditar saldo, negativo para debitarlo."),
    )
    descripcion = models.TextField(
        blank=True,
        verbose_name=_("Descripción / Comentario"),
        help_text=_("Motivo o detalle del ajuste."),
    )
    usuario = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='ajustes_cuenta',
        verbose_name=_("Usuario"),
        help_text=_("Usuario que registró el ajuste."),
    )
    creado_en = models.DateTimeField(auto_now_add=True, verbose_name=_("Creado el"))

    class Meta:
        verbose_name = _("Ajuste de cuenta")
        verbose_name_plural = _("Ajustes de cuenta")
        ordering = ('-fecha', '-id')

    def __str__(self):
        sign = '+' if self.monto >= 0 else ''
        medio = str(self.medio_de_pago) if self.medio_de_pago else '-'
        return f'Ajuste {sign}{self.monto} — {medio}'


