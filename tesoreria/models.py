def medios_permitidos_para(user):
    """Return the queryset of payment methods a cashier may operate.

    - Superusers see every payment method.
    - A cashier with no assignments sees every payment method (compat).
    - Otherwise, only active assignments are returned.
    """
    qs = MedioDePago.objects.all().order_by('nombre')
    if not user or not user.is_authenticated:
        return qs.none()
    if user.is_superuser:
        return qs
    asignaciones = AsignacionMedioPagoCajero.objects.filter(user=user)
    if not asignaciones.exists():
        return qs
    return qs.filter(asignaciones_cajero__user=user, asignaciones_cajero__activo=True).distinct()


def get_efectivo_default():
    """First payment method with ``Efectivo`` category, used by retiros and openings."""
    return MedioDePago.objects.filter(categoria='Efectivo').order_by('id').first()


